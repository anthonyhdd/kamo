-- 1. LQIP — the placeholder the slide can paint in zero milliseconds.
--
-- A ~20px JPEG as a data URL (~500 bytes), generated by the page at publish from the same
-- board the real JPEG is encoded from, stored on the row, served with every feed page. The
-- slide paints it as a blurred background the instant it mounts, so a swipe on cellular lands
-- on the photo's own colours instead of on black. Nullable forever: every existing hide and
-- every publish from a page loaded before this deploy simply has none, and the slide falls
-- back to today's behaviour.
